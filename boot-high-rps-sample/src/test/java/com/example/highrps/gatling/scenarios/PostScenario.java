package com.example.highrps.gatling.scenarios;

import static io.gatling.javaapi.core.CoreDsl.*;
import static io.gatling.javaapi.http.HttpDsl.*;

import com.example.highrps.gatling.feeders.AuthorFeeder;
import io.gatling.javaapi.core.ChainBuilder;
import java.util.UUID;

public class PostScenario {

    /**
     * Builds the post creation and verification flow.
     *
     * @return the Gatling scenario chain
     */
    public static ChainBuilder create() {
        return feed(AuthorFeeder.get())
                .exec(session -> {
                    String uuid = UUID.randomUUID().toString();
                    return session.set("idempotencyKey", uuid)
                            .set("randomTitle", "Gatling Post " + uuid.substring(0, 8));
                })
                .exec(http("Create Post")
                        .post("/api/posts")
                        .header("Idempotency-Key", "#{idempotencyKey}")
                        .body(
                                StringBody(
                                        "{\"title\":\"#{randomTitle}\", \"content\":\"Generated by load test\", \"email\":\"#{email}\", \"details\":{\"detailsKey\":\"Test details\",\"createdBy\":\"Gatling\"}, \"tags\":[{\"tagName\":\"gatling\"}, {\"tagName\":\"loadtest\"}]}"))
                        .check(status().is(201))
                        .check(header("Location").saveAs("postLocation")))
                .exec(session -> {
                    String location = session.getString("postLocation");
                    String postId = location.substring(location.lastIndexOf('/') + 1);
                    return session.set("newPostId", postId);
                })
                // functional check: verify created post
                .exec(http("Verify Created Post")
                        .get("#{postLocation}")
                        .check(status().is(200))
                        .check(jsonPath("$.authorEmail").is(session -> session.getString("email")))
                        .check(jsonPath("$.tags[0].tagName").is("gatling")));
    }
}
